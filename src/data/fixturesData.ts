/**
 * Récupère le fixture officiel et cohérent pour un club donné
 */
export function getClubUpcomingFixture(clubName: string, positionCode: 'GK' | 'DEF' | 'MID' | 'FWD' = 'MID', l5Score: number = 45): UpcomingFixture {
  const norm = normalizeClubName(clubName);
  const def = FIXTURES_CATALOG[norm] || FIXTURES_CATALOG['Club Non Renseigné'];

  const currentGW = getCurrentGameWeekNumber();
  const weeksDiff = currentGW - GAME_WEEK_ANCHOR.number;
  
  let newKickoffDate = def.kickoffDate;
  let newFormatted = def.kickoffFormatted;
  let newRelative = def.kickoffRelative;

  if (weeksDiff > 0 && def.kickoffDate) {
    const d = new Date(def.kickoffDate);
    if (!isNaN(d.getTime())) {
      d.setDate(d.getDate() + (weeksDiff * GAME_WEEK_ANCHOR.lengthDays));
      newKickoffDate = d.toISOString();
      const formatter = new Intl.DateTimeFormat('fr-FR', {
        timeZone: 'Europe/Paris',
        weekday: 'short',
        day: 'numeric',
        month: 'short',
        hour: '2-digit',
        minute: '2-digit'
      });
      // Try to re-create something like 'Sam. 22 août à 21:00'
      const parts = formatter.formatToParts(d);
      const wd = parts.find(p => p.type === 'weekday')?.value || '';
      const day = parts.find(p => p.type === 'day')?.value || '';
      const mo = parts.find(p => p.type === 'month')?.value || '';
      const hr = parts.find(p => p.type === 'hour')?.value || '';
      const min = parts.find(p => p.type === 'minute')?.value || '';
      newFormatted = `${wd.charAt(0).toUpperCase() + wd.slice(1)}. ${day} ${mo} à ${hr}:${min}`;
      
      const now = new Date();
      const daysTo = Math.ceil((d.getTime() - now.getTime()) / (1000 * 60 * 60 * 24));
      if (daysTo === 0) newRelative = 'Aujourd\'hui';
      else if (daysTo === 1) newRelative = 'Demain';
      else if (daysTo > 1) newRelative = `Dans ${daysTo} jours`;
      else newRelative = 'Terminé';
    }
  }

  const projScore = Math.max(20, Math.min(95, Math.round((
    (l5Score > 0 ? l5Score : 45) +
    (def.isHome ? 3.5 : -2.5) +
    (3 - def.difficultyRating) * 2.5 +
    (def.winProb >= 60 ? 3 : def.winProb <= 25 ? -3 : 0)
  ) * 10) / 10));

  // Weather determination based on country/club or custom override
  const weather: WeatherCondition = def.weather || {
    temperature: def.country === 'England' || def.country === 'Scotland' ? 17 : def.country === 'Spain' || def.country === 'Italy' ? 26 : 21,
    description: def.country === 'England' ? 'Pluie fine / Terrain gras' : def.country === 'Spain' ? 'Ensoleillé / Météo idéale' : 'Ciel dégagé',
    wind: def.country === 'England' || def.country === 'Netherlands' ? 24 : 12,
    isRainy: def.country === 'England',
  };

  return {
    gameWeek: currentGW,
    opponent: def.opponent,
    isHome: def.isHome,
    difficultyRating: def.difficultyRating,
    kickoffDate: newKickoffDate,
    matchDate: newKickoffDate,
    kickoffFormatted: newFormatted,
    kickoffRelative: newRelative,
    hasUpcomingMatch: def.hasUpcomingMatch,
    competitionName: def.competitionName,
    projectedScore: projScore,
    weather,
    bookmaker: {
      homeTeamName: def.isHome ? norm : def.opponent,
      awayTeamName: def.isHome ? def.opponent : norm,
      sourceType: 'estimated_mirror',
      source: 'Estimation interne (aucune source bookmaker réelle)',
      win: def.winOdds,
      draw: def.drawOdds,
      loss: def.lossOdds,
      cleanSheetProb: positionCode === 'GK' || positionCode === 'DEF' ? def.cleanSheetProb : Math.min(45, def.cleanSheetProb),
      goalExpectancy: positionCode === 'FWD' || positionCode === 'MID' ? def.goalExpectancy : Math.min(1.5, def.goalExpectancy),
      anytimeScorerOdds: def.anytimeScorerOdds,
    },
  };
}
